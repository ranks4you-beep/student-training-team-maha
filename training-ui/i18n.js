const translationPattern = new RegExp('(?<![\u0600-\u06ff])(?:' + Object.keys(EN).sort((a,b)=>b.length-a.length).map(key=>key.replace(/[.*+?^${}()|[\]\\]/g,'\\$&')).join('|') + ')(?![\u0600-\u06ff])','g');

function tr(text){ return language==='en' ? (EN[text] ?? text) : text; }

function translateUI(text){ return language==='en' ? text.replace(translationPattern,source=>EN[source]) : text; }

function ui(parts,...values){return parts.reduce((result,part,index)=>result+translateUI(part)+(index<values.length?values[index]:''),'');}

function currentLocale(){ return language==='en'?'en-GB':'ar-SA-u-ca-gregory'; }

function eventCount(count){return language==='en'?`${count} ${count===1?'event':'events'}`:`${count} فعالية`;}

function applyLanguage(){

  document.documentElement.lang=language;

  document.documentElement.dir=language==='en'?'ltr':'rtl';

  document.querySelectorAll('[data-i18n]').forEach(node=>node.textContent=translateUI(node.dataset.i18n));

  const button=document.getElementById('languageToggle');

  const name=document.getElementById('languageName');

  name.textContent=language==='ar'?'English':'العربية';

  name.lang=language==='ar'?'en':'ar';

  name.dir=language==='ar'?'ltr':'rtl';

  button.setAttribute('aria-label',tr(language==='ar'?'تغيير لغة الواجهة إلى الإنجليزية':'تغيير لغة الواجهة إلى العربية'));

  button.title=button.getAttribute('aria-label');

}

